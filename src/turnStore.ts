import * as fs from "node:fs";
import * as path from "node:path";
import type { Logger } from "./log";
import type { DiagramDto, Mode, PlanStep, TraceStepDto } from "./protocol";

/**
 * Turn records: one turn = intent-analysis result + user input + AI answer + tools used + files changed.
 *
 * Why store it separately: context compaction needs an "intent-based summary", which requires knowing
 * **what the user wanted** each turn, while the session JSONL only has message text. Line numbers align
 * with the JSONL (messageIndex), so rolling back the chat is just truncating by line number.
 *
 * Storage: `<sessions>/<sessionId>.turns.jsonl`, one turn per line, append-only.
 */
export interface TurnRecord {
  /** One-sentence user intent produced by intent analysis */
  intent: string;
  mode: Mode;
  /** Task scale judged by intent analysis (to restore lastIntent after a rollback) */
  scale?: "small" | "large";
  /** Whether intent analysis said "a proposal should be produced" */
  needsProposal?: boolean;
  /** Reason for the intent verdict */
  reason?: string;
  /** Consumption of this turn (cumulative) */
  inputTokens?: number;
  outputTokens?: number;
  elapsedMs?: number;
  modelWaitMs?: number;
  toolMs?: number;
  /** The user's own words (truncated) */
  userText: string;
  /** The AI's answer for this turn (truncated) */
  assistant: string;
  /** Tools called during this turn (deduplicated, excluding model/guard) */
  tools: string[];
  /** Files involved in proposals produced by this turn (deduplicated) */
  files: string[];
  /** Tool observation summaries (name: summary), for the model to consult when summarizing */
  observations: string[];
  /** The final plan of this turn (carried across turns) */
  plan?: PlanStep[];
  /** Diagrams generated by this turn (included in the summary) */
  diagrams?: DiagramDto[];
  /** This turn's trace (thinking / tools / diagrams), used for the collapsible card under the user message */
  trace?: TraceStepDto[];
  /** Whether this turn ended normally */
  status?: "ok" | "error";
  error?: string;
  /** Id of this turn's user message (for trace navigation) */
  userMessageId?: string;
  ts: number;
  /** Number of session JSONL entries when this turn was written (for rollback truncation) */
  messageIndex: number;
}

export class TurnStore {
  constructor(
    private readonly dir: string,
    private readonly logger: Logger,
  ) {
    try {
      fs.mkdirSync(dir, { recursive: true });
    } catch (err) {
      this.logger.warn(`轮次目录创建失败: ${err instanceof Error ? err.message : String(err)}`);
    }
  }

  private fileOf(sessionId: string): string {
    const safe = sessionId.replace(/[^a-zA-Z0-9_.-]/g, "_").slice(0, 80);
    return path.join(this.dir, `${safe}.turns.jsonl`);
  }

  async append(sessionId: string, record: TurnRecord): Promise<void> {
    try {
      await fs.promises.appendFile(this.fileOf(sessionId), `${JSON.stringify(record)}\n`, "utf8");
    } catch (err) {
      this.logger.warn(`轮次记录写入失败: ${err instanceof Error ? err.message : String(err)}`);
    }
  }

  async list(sessionId: string): Promise<TurnRecord[]> {
    let raw: string;
    try {
      raw = await fs.promises.readFile(this.fileOf(sessionId), "utf8");
    } catch {
      return [];
    }
    const out: TurnRecord[] = [];
    for (const line of raw.split("\n")) {
      const trimmed = line.trim();
      if (!trimmed) continue;
      try {
        const parsed = JSON.parse(trimmed) as TurnRecord;
        if (typeof parsed.intent === "string" && typeof parsed.messageIndex === "number") out.push(parsed);
      } catch {
        // Corrupt partial line: ignore
      }
    }
    return out;
  }

  /** Chat rollback: keep turns whose messageIndex <= the limit */
  async truncate(sessionId: string, maxMessageIndex: number): Promise<void> {
    const turns = await this.list(sessionId);
    const kept = turns.filter((turn) => turn.messageIndex <= maxMessageIndex);
    if (kept.length === turns.length) return;
    const body = kept.map((turn) => JSON.stringify(turn)).join("\n") + (kept.length > 0 ? "\n" : "");
    const file = this.fileOf(sessionId);
    const tmp = `${file}.tmp`;
    try {
      await fs.promises.writeFile(tmp, body, "utf8");
      await fs.promises.rename(tmp, file);
      this.logger.info(`轮次记录截断：${turns.length} → ${kept.length}`);
    } catch (err) {
      this.logger.warn(`轮次记录截断失败: ${err instanceof Error ? err.message : String(err)}`);
      await fs.promises.rm(tmp, { force: true }).catch(() => undefined);
    }
  }

  async clear(sessionId: string): Promise<void> {
    try {
      await fs.promises.rm(this.fileOf(sessionId), { force: true });
    } catch {
      // If the file does not exist, never mind
    }
  }
}
